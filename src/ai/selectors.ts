// ─── Flattened views, envelope first with a legacy fallback ──────────────────
//
// Surfaces that predate the Marketing Studio (the post editor's AI panel) want
// one caption, one flat tag list and one caption per platform. These read the
// envelope when it's there and fall back to the original columns, so a post
// generated by either pipeline renders the same.

/** Best single caption: the first studio variation, else the legacy caption. */
export function getPrimaryCaption(post: LegacyBearing): string | null {
  const variation = post.ai_studio_output?.contentVariations?.variations?.[0];
  return variation?.caption ?? post.ai_caption ?? null;
}

/**
 * Every hashtag as a flat, de-duplicated list without the leading `#`.
 * Legacy rows sometimes hold one merged string ("tag1, tag2"), so split those.
 */
export function getFlatHashtags(post: LegacyBearing): string[] {
  const groups = post.ai_studio_output?.hashtagGroups?.groups;
  const tags = groups
    ? groups.flatMap((group) => group.hashtags.map((hashtag) => hashtag.tag))
    : (post.ai_hashtags ?? []).flatMap((tag) => tag.split(/[,\s#]+/));
  return [...new Set(tags.map((tag) => tag.replace(/^#/, "")).filter(Boolean))];
}

/** One caption per platform, keyed by platform id. */
export function getPlatformCaptions(post: LegacyBearing): Record<string, string> {
  const variations = post.ai_studio_output?.platformVariations;
  const source = variations
    ? Object.fromEntries(
        Object.entries(variations).map(([platform, v]) => [platform, v.caption]),
      )
    : (post.ai_platform_content ?? {});

  return Object.fromEntries(
    Object.entries(source).filter((entry): entry is [string, string] =>
      Boolean(entry[1]),
    ),
  );
}
