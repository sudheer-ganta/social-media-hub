/**
 * Read helpers for the AI Marketing Studio envelopes.
 *
 * Components never reach into post.ai_studio_output directly — going through
 * these keeps the envelope shape in one place, so bumping
 * STUDIO_SCHEMA_VERSION means fixing these functions and nothing else.
 */

import {
  EMPTY_GENERATION_META,
  STUDIO_OUTPUT_KEYS,
  type AiStudioInput,
  type AiStudioOutput,
  type CampaignPlan,
  type CompetitorAnalysis,
  type ContentVariations,
  type CtaOptions,
  type GenerationMeta,
  type HashtagGroups,
  type ImageAnalysis,
  type PlatformVariations,
  type SeoAnalysis,
  type StudioOutputKey,
} from "./types";

/** Minimal shape these helpers need — avoids a circular import on Post. */
interface StudioBearing {
  ai_studio_input?: AiStudioInput | null;
  ai_studio_output?: AiStudioOutput | null;
}

/** Adds the pre-studio columns, still written by the original Make scenario. */
interface LegacyBearing extends StudioBearing {
  ai_caption?: string | null;
  ai_hashtags?: string[] | null;
  ai_platform_content?: Record<string, string | undefined> | null;
}

export function getStudioInput(post: StudioBearing): AiStudioInput | null {
  return post.ai_studio_input ?? null;
}

export function getStudioOutput(post: StudioBearing): AiStudioOutput | null {
  return post.ai_studio_output ?? null;
}

export function getGenerationMeta(post: StudioBearing): GenerationMeta {
  return post.ai_studio_output?.meta ?? EMPTY_GENERATION_META;
}

/** True when the generation failed outright or only partly succeeded. */
export function hasGenerationError(post: StudioBearing): boolean {
  const status = getGenerationMeta(post).status;
  return status === "failed" || status === "partial";
}

/** Which output sections this post actually has content for. */
export function producedKeys(post: StudioBearing): StudioOutputKey[] {
  const output = post.ai_studio_output;
  if (!output) return [];
  return STUDIO_OUTPUT_KEYS.filter((key) => output[key] != null);
}

/** True when Make wrote back at least one generated section. */
export function hasStudioOutput(post: StudioBearing): boolean {
  return producedKeys(post).length > 0;
}

