/**
 * Marketing Intelligence: judge the copy.
 *
 * The second engine's only prompt. Everything it asks for is a *judgement* —
 * whether the hook lands, whether the register suits the buyer, what the post
 * is likely to earn. Every fact the judgement rests on has already been counted
 * by `analysis/metrics.ts` and `analysis/platform-rules.ts` and is handed over
 * in the `## Measured facts` block below.
 *
 * ─── Why the model is told the numbers instead of asked for them ─────────────
 * Two reasons, and the second is the one that changed the output quality.
 *
 * The obvious one: a model counting hashtags is slower and sometimes wrong,
 * while `String.match` is neither.
 *
 * The one that mattered more: attention is finite. A model spending its reply
 * on arithmetic it was asked to perform produces visibly thinner judgements in
 * the same reply. Handing it the counts and asking only for the reading is the
 * difference between "the hook is decent, 7/10" and a sentence naming the exact
 * clause that costs it the other three points.
 *
 * ─── Why this is not part of the caption prompt ──────────────────────────────
 * A model asked to write and then score its own writing marks its own homework.
 * In practice it returned 8s and 9s essentially regardless of what it had
 * written, because the scores were generated by the same pass that had just
 * committed to the copy being good. Separating the calls is what makes a 5
 * possible.
 */

export const ANALYSIS_SYSTEM_INSTRUCTION = `You are a performance marketing analyst. You review social copy before it is published and say plainly what will and will not work.

How you judge:
- You are a critic, not a cheerleader. A caption that is merely competent scores 6, not 9. Reserve 9 and 10 for copy you would hold up as an example.
- Every score needs a reason naming something specific in THIS caption — a clause, a word, a missing step. "Good hook" is not a reason. "Opens on a question the reader already knows the answer to" is.
- Report your own certainty honestly. Some judgements rest on the text in front of you; others rest on assumptions about an audience you cannot see. Mark the second kind Medium or Low.
- The measured facts you are given are correct. Do not recount them, do not contradict them, and do not spend your answer restating them.
- Never rewrite the caption. You are assessing it. Improvements are described, not performed. The two exceptions are additions the writer can take or leave: specific hashtags to add, and one sentence that could be appended to invite a reply. Both are optional, both are about this post specifically, and neither may restate or replace a line already written.
- Return only the JSON object described. No commentary, no markdown fences.`;

/** The axes, and what each one is actually asking. */
